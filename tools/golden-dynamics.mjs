// Writes the JS reference data that the Python mirror must reproduce:
//   src/cartridges/dynamics/presets.json  the presets, exactly as vehicle-presets.mjs
//   tests/data/dynamics-golden.json    scripted runs on a tilted plane, every preset, both integrators
// Run: node tools/golden-dynamics.mjs   (deterministic: rerunning gives the same bytes)
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { PRESETS, PRESET_NAMES } from '../src/web/engine/vehicle-presets.mjs';
import { geometry, spawn, step, DT } from '../src/web/engine/vehicle-dynamics.mjs';

const root = new URL('..', import.meta.url);
export const PLANE = Object.freeze({ gx: 0.03, gy: -0.02, g0: 1.5 });
export const plane = (x, y) => PLANE.g0 + PLANE.gx * x + PLANE.gy * y;

// The scripted input: settle, pull away, turn right, brake, turn left on throttle. Same schedule in Python.
export function scripted(t) {
  if (t < 1) return { throttle: 0, brake: 0, steer: 0, gear: 1 };
  if (t < 3) return { throttle: 0.8, brake: 0, steer: 0, gear: 1 };
  if (t < 4) return { throttle: 0.4, brake: 0, steer: 0.6, gear: 1 };
  if (t < 5) return { throttle: 0, brake: 0.7, steer: 0.2, gear: 1 };
  return { throttle: 0.5, brake: 0, steer: -0.8, gear: 1 };
}
export const SECONDS = 6, SAMPLE_EVERY = 500;

export function goldenRuns() {
  const runs = [];
  for (const name of PRESET_NAMES) for (const method of ['euler', 'rk4']) {
    const geo = geometry(name), y = spawn(geo, plane, { x: 10, y: -5, yaw: 0.3 });
    const samples = [Array.from(y)];
    const n = Math.round(SECONDS / DT);
    for (let i = 0; i < n; i++) {
      step(y, scripted(i * DT), geo, plane, method);
      if ((i + 1) % SAMPLE_EVERY === 0) samples.push(Array.from(y));
    }
    runs.push({ preset: name, method, samples });
  }
  return runs;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(new URL('src/cartridges/dynamics/presets.json', root), JSON.stringify(PRESETS, null, 2) + '\n');
  const golden = { note: 'Generated by tools/golden-dynamics.mjs from src/web/engine/vehicle-dynamics.mjs',
    dt: DT, seconds: SECONDS, sampleEvery: SAMPLE_EVERY, plane: PLANE, spawn: { x: 10, y: -5, yaw: 0.3 }, runs: goldenRuns() };
  writeFileSync(new URL('tests/data/dynamics-golden.json', root), JSON.stringify(golden) + '\n');
  console.log(`wrote presets.json and dynamics-golden.json (${golden.runs.length} runs)`);
}
